def grid(text):
    rows = [r for r in text.strip("\n").split("\n")]
    width = max(len(r) for r in rows)
    return [r.ljust(width, ".") for r in rows]


def mac(face):
    f = grid(FACES[face])
    out, fy = [], 0
    for row in grid(MAC):
        if "S" in row:
            i = row.index("S")
            row = row[:i] + f[fy] + row[i + 16:]
            fy += 1
        out.append(row)
    return out


def floppy(question):
    """A 3.5" disk, 20×22, with an optional '?' on the label."""
    w, h = 20, 22
    px = [["." for _ in range(w)] for _ in range(h)]
    for x in range(w):
        px[0][x] = px[h - 1][x] = "#"
    for y in range(h):
        px[y][0] = px[y][w - 1] = "#"
    px[0][w - 1] = px[1][w - 1] = px[0][w - 2] = "."  # chamfered corner
    px[1][w - 2] = "#"
    for y in range(0, 8):       # metal shutter with its window
        for x in range(5, 15):
            px[y][x] = "#"
    for y in range(1, 7):
        for x in range(10, 13):
            px[y][x] = "."
    for x in range(2, 18):      # label
        px[10][x] = "#"
    for y in range(10, h):
        px[y][2] = px[y][17] = "#"
    if question:
        q = grid(QUESTION)
        for dy, row in enumerate(q):
            for dx, ch in enumerate(row):
                if ch == "#":
                    px[12 + dy][8 + dx] = "#"
    return ["".join(r) for r in px]


def scale(rows, k):
    return ["".join(ch * k for ch in r) for r in rows for _ in range(k)]


def xbm(rows):
    """XBM: rows padded to whole bytes, least significant bit = leftmost pixel."""
    data = []
    for r in rows:
        for b in range(0, len(r), 8):
            chunk = r[b:b + 8]
            data.append(sum(1 << i for i, ch in enumerate(chunk) if ch == "#"))
    return data


ART = {
    "mac_happy": mac("happy"),
    "mac_blink": mac("blink"),
    "mac_sad": mac("sad"),
    "mac_off": mac("off"),
    "floppy_q": floppy(True),
    "floppy": floppy(False),
    "bomb": grid(BOMB),
    "bluetooth": grid(BLUETOOTH),
    "keyboard": grid(KEYBOARD),
    "mouse": grid(MOUSE),
}
SMALL = {"bluetooth", "keyboard", "mouse"}  # status-bar icons stay 1x


def main():
    lines = [
        "// Generated by scripts/make-oled-art.py — edit the drawings there, not here.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "struct Art { uint8_t w, h; const uint8_t* bits; };",
        "",
    ]
    for name, rows in ART.items():
        for k in (1,) if name in SMALL else (1, 2):
            r = scale(rows, k)
            data = xbm(r)
            ident = f"{name}_{k}x"
            body = ", ".join(f"0x{b:02x}" for b in data)
            lines.append(f"static const uint8_t {ident}_bits[] = {{{body}}};")
            lines.append(f"static const Art ART_{ident.upper()} = {{{len(r[0])}, {len(r)}, {ident}_bits}};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(ART)} drawings)")


if __name__ == "__main__":
    main()
