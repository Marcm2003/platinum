// Generates docs/hardware.md from the same wiring data the app uses (src/lib/hardware),
// so the document can't drift from the in-app diagram.
//   node scripts/gen-hardware-docs.mjs

import { build } from "esbuild";
import { writeFileSync } from "node:fs";

const entry = `
export { buildWiring } from "./src/lib/hardware/wiring";
export { BOARDS, boardBuildFlags } from "./src/lib/hardware/boards";
export { CONNECTORS } from "./src/lib/hardware/connectors";
export { MAC_MODELS } from "./src/lib/hardware/macModels";
`;
await build({ stdin: { contents: entry, resolveDir: ".", loader: "ts" }, bundle: true, platform: "node", format: "esm", outfile: "node_modules/.cache/hardware.mjs", logLevel: "warning" });
const { buildWiring, BOARDS, boardBuildFlags, CONNECTORS, MAC_MODELS } = await import(new URL("../node_modules/.cache/hardware.mjs", import.meta.url).href);

const md = [];
const table = (head, rows) => {
  md.push(`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`);
  for (const r of rows) md.push(`| ${r.map((c) => String(c).replace(/\|/g, "\\|")).join(" | ")} |`);
  md.push("");
};

md.push(
  "<!-- Generated by scripts/gen-hardware-docs.mjs from src/lib/hardware. Edit those files, then re-run the script. -->",
  "",
  "# Building the Platinum Bridge",
  "",
  "The bridge is an ESP32 board between your classic Mac and your computer. Depending on what you wire up it can:",
  "",
  "- **Be the Mac's keyboard and mouse** — an ADB keyboard + mouse (Macintosh SE and later) or an M0110 keyboard + quadrature mouse (128K, 512K, Plus). Type from Platinum, or pair any Bluetooth LE keyboard and mouse with the bridge.",
  "- **Carry the Mac's serial port over WiFi, USB or Bluetooth** — this is what Platinum Agent uses for file transfer, the remote screen and the debugger.",
  "- **Power the Mac on** from the app (ADB machines with a soft-power key: Mac II, LC, Quadra…).",
  "",
  "The **Hardware & link** page in Platinum draws this same wiring interactively for your exact Mac and board. This document is the printable version.",
  "",
  "> [!WARNING]",
  "> Classic Macs are 30+ years old and their parts are irreplaceable. Check every pin of every cable with a multimeter before plugging it in, never connect +12 V to anything, and keep the ESP32's 3.3 V logic away from the Mac's 5 V lines — always go through the level shifter or transceiver listed here.",
  "",
  "## Contents",
  "",
  "- [Pick a board](#pick-a-board)",
  "- [Wiring by Mac family](#wiring-by-mac-family)",
  "- [Connector pinouts](#connector-pinouts)",
  "- [Flashing the firmware](#flashing-the-firmware)",
  "- [First power-on checklist](#first-power-on-checklist)",
  "- [Photos of finished bridges](#photos-of-finished-bridges)",
  "",
  "## Pick a board",
  "",
);
table(["Board", "Chip", "Bluetooth", "Notes"], BOARDS.map((b) => [`**${b.name}**`, b.chip, b.bluetooth, b.notes]));
md.push("### Pin map", "", "The firmware uses these GPIOs (see `firmware/platinum-bridge/config.h`).", "");
const roles = Object.keys(BOARDS[0].roles).filter((r) => !r.startsWith("I2S"));
table(["Signal", ...BOARDS.map((b) => b.name)], roles.map((r) => [`\`${r}\``, ...BOARDS.map((b) => (b.roles[r] >= 0 ? `GPIO ${b.roles[r]}` : "—"))]));
md.push(
  "On ESP32-C3 boards only 13 GPIOs reach the headers, so the ADB pins (Macintosh SE and later) and the M0110 keyboard pins (128K, 512K, Plus) are the same two GPIOs: a Mac only ever uses one of the two buses. The C3 is single-core, which makes ADB timing tighter than on the S3; it's the cheapest option, and best suited to M0110 Macs and the serial link.",
  "",
  "### Status screen",
  "",
  "The firmware shows the bridge's status on an SSD1306 OLED: whether the Mac is polling, how Platinum is connected, the IP address, paired Bluetooth devices and serial traffic. Press **BOOT** to switch pages.",
  "",
);
table(["Board", "Screen", "I2C pins"], BOARDS.map((b) => [b.name, b.display.kind === "builtin-72x40" ? "Built-in 0.42\" (72×40)" : "Optional 0.96\" (128×64), detected at start-up", `SDA GPIO ${b.display.sda}, SCL GPIO ${b.display.scl}`]));
md.push(
  '<p align="center"><img src="images/oled/72x40-tour.gif" width="432" alt="The status screen: start-up, then the little Mac reacting to the bridge"></p>',
  "",
  "A little Mac on the home page tells you how things are, in the spirit of the classic start-up icons:",
  "",
);
const shot = (name) => `<img src="images/oled/72x40-${name}.png" width="216" alt="">`;
table(["Screen", "Meaning"], [
  [shot("boot_welcome"), "Starting up: Bluetooth, then WiFi. After a crash, the classic system-error box with the bomb comes first (ID = the reset reason: panic, watchdog or power)."],
  [shot("home_no_mac"), "No Mac has talked to the bridge yet. Check the bus cable and that the Mac is on."],
  [shot("home_mac_ok"), "The Mac is polling the bridge. Keyboard and mouse icons light up as you type and move."],
  [shot("home_mac_asleep"), "The Mac was there but has gone quiet: it's off, asleep or unplugged."],
  [shot("home_error"), "Something failed. The code says what: `00000001` couldn't join WiFi (the bridge falls back to its own access point), `00000002` Bluetooth pairing failed."],
  [shot("bomb"), "Shown at start-up if the bridge restarted after a crash."],
]);
md.push("Regenerate these with `npm run oled-preview`: it renders the firmware's own drawing code on your computer.", "");

md.push("## Wiring by Mac family", "", "Each family below shows the ESP32-S3 wiring with keyboard/mouse and the serial port enabled, powered over USB. For the classic ESP32 swap the GPIO numbers using the pin map above.", "");
const families = [
  { id: "128k", title: "Macintosh 128K and 512K", also: "M0110 keyboard, quadrature mouse and a DE-9 serial port." },
  { id: "plus", title: "Macintosh Plus", also: "M0110 keyboard and quadrature mouse, mini-DIN-8 serial port." },
  { id: "se", title: "ADB Macs (SE, II, Classic, LC, Quadra, Power Macintosh…)", also: "ADB for keyboard and mouse and the mini-DIN-8 serial port. Shown for the Macintosh SE; every ADB model is wired the same way." },
];
for (const f of families) {
  const plan = buildWiring("esp32s3", f.id, { input: true, serial: true, power: "usb" });
  const models = MAC_MODELS.filter((m) => m.input === plan.model.input && m.serial === plan.model.serial).map((m) => m.name);
  md.push(`### ${f.title}`, "", f.also, "", `Applies to: ${models.join(", ")}.`, "");
  md.push("**Connections**", "");
  table(["Signal", "ESP32-S3", "Through", "Mac"], plan.table.map((r) => [r.signal, r.esp, r.via, r.mac]));
  md.push("**Parts**", "");
  table(["Qty", "Part", "Why"], plan.bom.map((b) => [b.qty, b.part, b.why]));
  md.push("**Before you plug in**", "", ...plan.warnings.map((w) => `- ${w}`), "");
}
md.push(
  "### Powering the bridge from the Mac",
  "",
  "On ADB Macs the bridge can run from the ADB port's +5 V instead of USB (toggle **Mac power** in the app). The whole ADB bus has 500 mA, and the ESP32's WiFi draws spikes, so add a 470 µF / 10 V electrolytic capacitor across +5 V and GND and keep other ADB devices to a minimum. On the Mac Plus and earlier, power the bridge over USB.",
  "",
  "## Connector pinouts",
  "",
  "All drawings in Platinum show the **front of the socket on the Mac**, looking into it.",
  "",
);
for (const c of Object.values(CONNECTORS)) {
  md.push(`### ${c.name}`, "", c.note, "");
  table(["Pin", "Name", "Description"], [...c.pins].sort((a, b) => a.n - b.n).map((p) => [p.n, `\`${p.name}\``, p.desc]));
}
md.push(
  "## Flashing the firmware",
  "",
  "**The quick way:** every release includes a ready-to-flash image per board, `platinum-bridge-<board>.bin`. Open [ESP Tool](https://espressif.github.io/esptool-js/) in Chrome or Edge, connect the board, and write the file at offset `0x0`. No toolchain needed.",
  "",
  "**From source:** the firmware is an Arduino sketch in `firmware/platinum-bridge/`. Platinum's **Hardware & link → Firmware** tab runs these commands for you, and `npm run firmware` builds the images for every board. By hand they are:",
  "",
  "```sh",
  "arduino-cli core install esp32:esp32",
  'arduino-cli lib install "NimBLE-Arduino" "WebSockets" "ArduinoJson" "U8g2"',
  "",
  ...BOARDS.map((b) => `# ${b.name}\narduino-cli compile --fqbn ${b.fqbn}${boardBuildFlags(b)} firmware/platinum-bridge\narduino-cli upload -p <port> --fqbn ${b.fqbn} firmware/platinum-bridge`),
  "```",
  "",
  "`<port>` is `COM5` or similar on Windows, `/dev/cu.usbmodem…` on macOS and `/dev/ttyACM0` on Linux. If an ESP32-S3 isn't detected the first time, hold **BOOT**, tap **RST** and release **BOOT**.",
  "",
  "With no WiFi configured the bridge starts an access point called `Platinum-XXXX` (password `macintosh`) at 192.168.4.1. Send it your network's credentials from **Hardware & link → Bridge & network**; after a restart it shows up as `platinum.local`.",
  "",
  "## First power-on checklist",
  "",
  "1. Mac **off**. Bridge connected to your computer over USB only.",
  "2. Flash the firmware and connect from Platinum over USB. The bridge log should say `Platinum Bridge v… ready`.",
  "3. Check continuity of every wire against the tables above, and that nothing touches +12 V.",
  "4. Plug the bridge into the Mac and switch the Mac on.",
  "5. On **Keyboard & mouse**, the bus monitor should show the Mac polling the bridge within a couple of seconds. If it doesn't, re-check the data line and the level shifter's HV/LV supply.",
  "6. Click the remote-control area and move the mouse: the Mac's pointer should follow.",
  "",
  "## Photos of finished bridges",
  "",
  "_Coming soon._ If you build one, please open a pull request adding a photo to `docs/images/` and a line here — breadboard builds welcome.",
  "",
);

writeFileSync("docs/hardware.md", md.join("\n"));
console.log("wrote docs/hardware.md");
