/** Compare two MacRoman names the way the HFS catalog does (RelString-like). */
export function relString(a: Uint8Array, b: Uint8Array): number {
  const n = Math.min(a.length, b.length);
  for (let i = 0; i < n; i++) {
    const d = CHARORDER[a[i]] - CHARORDER[b[i]];
    if (d) return d;
  }
  return a.length - b.length;
}

export const sameHfsName = (a: string, b: string) => relString(encodeMacRoman(a, 31), encodeMacRoman(b, 31)) === 0;
