const toUni: string[] = [];
const fromUni = new Map<string, number>();
for (let i = 0; i < 256; i++) {
  const ch = i < 128 ? String.fromCharCode(i) : HIGH[i - 128];
  toUni.push(ch);
  fromUni.set(ch, i);
}

export function decodeMacRoman(bytes: Uint8Array): string {
  let s = "";
  for (const b of bytes) s += toUni[b];
  return s;
}

export function encodeMacRoman(s: string, max = Infinity): Uint8Array {
  const out: number[] = [];
  for (const ch of s.normalize("NFC")) {
    if (out.length >= max) break;
    out.push(fromUni.get(ch) ?? (ch === "/" ? 0x3a : 0x3f)); // unmappable -> '?'
  }
  return new Uint8Array(out);
}

/** HFS name rules: 1..31 MacRoman bytes, no colon. */
export function sanitizeHfsName(s: string, max = 31): string {
  const clean = s.replace(/:/g, "-").trim() || "untitled";
  return decodeMacRoman(encodeMacRoman(clean, max));
}

